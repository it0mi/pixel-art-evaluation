"""
Generates JSON file with image pairs.
Pairs are then used in the web app for pairwise evaluation.

Author: Tomáš Kurtin (xkurti03@stud.fit.vut.cz)
Date: 5 May 2026
"""

import os
import json
import random
import sys
from itertools import combinations

#
# Configuration
#
if len(sys.argv) < 2:
    print("Usage:")
    print("\tpython pairGenerator.py config.json")

# Program can be run from user_testing or root directory
user_testing_root_dir = "user_testing/" if os.path.exists("src") else ""
conf_path = user_testing_root_dir + sys.argv[1]

# Load configuration file
with open(conf_path, "r") as file:
    conf = json.load(file)
if conf["runnable_from_root"]:
    ROOT_DIR = user_testing_root_dir + conf["input_root_dir"]
else:
    ROOT_DIR = conf["input_root_dir"]
METHODS = conf["methods"]
def_n = str(conf["default_color_limit"])
DEFAULT_COLOR_N = {"resizeReduce": def_n, "pia": def_n, "piaResize": def_n}
DEFAULT_COLOR_N_ENABLED = conf["color_limit_enabled"]
OUTPUT_FILE = conf["output_file"]
SHUFFLE_PAIRS = conf["shuffle_pairs"]
RANDOMIZE_LEFT_RIGHT = conf["shuffle_left_right"]
IMAGE_EXTENSIONS = conf["image_extensions"]


def get_method_root(method_name):
    """
    Get root path to method folder.

    :param method_name: Method name
    :return method_dir: Method directory
    """
    method_dir = os.path.join(ROOT_DIR, method_name)
    if not DEFAULT_COLOR_N_ENABLED:
        return method_dir

    # Switch to default color count if not using color reduction comparison
    if method_name in DEFAULT_COLOR_N:
        method = DEFAULT_COLOR_N[method_name]
        method_dir = os.path.join(method_dir, method)
        if os.path.exists(method_dir):
            return method_dir

    return method_dir


def get_all_images(method_name):
    """
    Return all images produced by method as dict.

    :param method_name: Method name
    :return images: Dictionary of all images
    """

    method_dir = get_method_root(method_name)

    if not os.path.exists(method_dir):
        print("Missing result directory -", method_dir)
        return {}

    images = {}

    for root, _, files in os.walk(method_dir):

        for file in files:

            # Image check
            ext = os.path.splitext(file)[1].lower()
            if ext not in IMAGE_EXTENSIONS:
                continue

            full_path = os.path.join(root, file)

            # Will function as a key for finding same results in different method folders
            key_path = os.path.relpath(full_path, method_dir)
            key_path = key_path.replace("\\", "/")

            images[key_path] = full_path.replace("\\", "/")
    return images


def generate_pairs():
    """
    Generate pairs.

    :return pairs: Array of pairs(JSONs)
    """

    method_images = {}

    for method in METHODS:
        method_images[method] = get_all_images(method)

    shared_keys = None

    # Find images, that were generated by all methods.
    for images in method_images.values():

        keys = set(images.keys())

        if shared_keys is None:
            shared_keys = keys
        else:
            shared_keys = shared_keys.intersection(keys)

    shared_keys = sorted(shared_keys)

    pairs = []
    pair_id = 0

    # Create all JSON elements
    for image_key in shared_keys:
        for exp_a, exp_b in combinations(METHODS, 2):

            path_a = method_images[exp_a][image_key]
            path_b = method_images[exp_b][image_key]

            left_image = path_a.replace("./../", "")
            left_image = left_image.replace("web/", "")
            right_image = path_b.replace("./../", "")
            right_image = right_image.replace("web/", "")

            left_method = exp_a
            right_method = exp_b

            if RANDOMIZE_LEFT_RIGHT:
                if random.random() < 0.5:  # 50% chance
                    tmp = left_image
                    left_image = right_image
                    right_image = tmp

                    tmp = left_method
                    left_method = right_method
                    right_method = tmp

            # JSON data
            pair = {
                "pair_id": pair_id,
                "left_image": left_image,
                "right_image": right_image,
                "left_method": left_method,
                "right_method": right_method,
            }

            pairs.append(pair)
            pair_id += 1

    if SHUFFLE_PAIRS:
        random.shuffle(pairs)

        i = 0
        for pair in pairs:
            pair["pair_id"] = i
            i += 1

    return pairs


def main():
    """
    Generate pairs and store them into json file.
    """
    pairs = generate_pairs()

    with open(OUTPUT_FILE, "w") as f:
        json.dump(pairs, f, indent=2)


if __name__ == "__main__":
    main()
